// Minimal i18n for the preferences UI. Dictionaries are keyed by the English
// source string; a missing entry falls back to English, so partially
// translated languages degrade gracefully. Aria-labels stay English on purpose
// (they are programmatic identifiers, not visible copy).
import type { Settings } from "./types";

export type Lang = "en" | "pt-BR" | "es";

export const LANGUAGES: { value: string; label: string }[] = [
  { value: "", label: "System default" },
  { value: "en", label: "English" },
  { value: "pt-BR", label: "Português (Brasil)" },
  { value: "es", label: "Español" },
];

// resolveLang maps the persisted Behavior.Language ("" = system default) to a
// supported language, sniffing navigator.language for the default.
export function resolveLang(setting: Settings["behavior"]["language"]): Lang {
  if (setting === "en" || setting === "pt-BR" || setting === "es") return setting;
  const nav = typeof navigator !== "undefined" ? (navigator.language ?? "en") : "en";
  if (nav.toLowerCase().startsWith("pt")) return "pt-BR";
  if (nav.toLowerCase().startsWith("es")) return "es";
  return "en";
}

export type Translate = (s: string) => string;

// makeT returns a translate function for the language. English is identity.
export function makeT(lang: Lang): Translate {
  if (lang === "en") return (s) => s;
  const dict = DICTS[lang];
  return (s) => dict[s] ?? s;
}

